/**
 * Helper function to get district for a neighborhood
 */
export function getDistrict(neighborhoodName: string): string | null {
  return NEIGHBORHOOD_DISTRICT[neighborhoodName] || null;
}

/**
 * Helper function to get color for a district
 */
export function getDistrictColor(district: string | null): string {
  if (!district) return 'rgba(100, 116, 139, 0.3)'; // default gray
  return DISTRICT_COLORS[district] || 'rgba(100, 116, 139, 0.3)';
}

/**
 * Helper function to get hover color for a district
 */
export function getDistrictColorHover(district: string | null): string {
  if (!district) return 'rgba(100, 116, 139, 0.5)';
  return DISTRICT_COLORS_HOVER[district] || 'rgba(100, 116, 139, 0.5)';
}

/**
 * Helper function to get selected color for a district
 */
export function getDistrictColorSelected(district: string | null): string {
  if (!district) return 'rgba(100, 116, 139, 0.7)';
  return DISTRICT_COLORS_SELECTED[district] || 'rgba(100, 116, 139, 0.7)';
}
